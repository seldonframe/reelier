import canonicalize from "canonicalize";
import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const contractDirectory = fileURLToPath(new URL("../contract/outcome-profile/v1/", import.meta.url));
const descriptorTarget = join(contractDirectory, "contract-descriptor.json");
const sourceTarget = fileURLToPath(new URL("../src/authority/outcome-profile-contract.ts", import.meta.url));
const members = [
  "profile-activation.schema.json",
  "profile-authority-evidence.schema.json",
  "profile-conformance-report.schema.json",
  "profile-conformance.schema.json",
  "profile-draft.schema.json",
  "profile-governance-manifest.schema.json",
  "profile-governed-receipt.schema.json",
  "profile-trust-pin.schema.json",
];

if (members.join("\0") !== [...members].sort().join("\0")) throw new Error("outcome profile contract members must be sorted");
if (new Set(members).size !== members.length) throw new Error("outcome profile contract members must be unique");
if (members.some(member => member.includes("/") || member.includes("\\") || member === "." || member === "..")) throw new Error("outcome profile contract member path is invalid");

const actual = (await readdir(contractDirectory, { withFileTypes: true }))
  .filter(entry => entry.isFile() && entry.name !== "contract-descriptor.json")
  .map(entry => entry.name)
  .sort();
if (actual.join("\0") !== members.join("\0")) throw new Error("outcome profile contract membership drift");

const digestedMembers = await Promise.all(members.map(async path => ({
  path,
  digest: `sha256:${createHash("sha256").update(normalizeBytes(await readFile(join(contractDirectory, path)))).digest("hex")}`,
})));
const unsigned = { v: "reelier.outcome-profile-contract/v1", domain: "reelier.outcome-profile-contract/v1\\0", members: digestedMembers };
const descriptor = { ...unsigned, digest: `sha256:${createHash("sha256").update(canonicalize(unsigned), "utf8").digest("hex")}` };
const renderedDescriptor = `${JSON.stringify(descriptor, null, 2)}\n`;
const renderedSource = renderSource(descriptor);

if (process.argv.includes("--check")) {
  if (normalizeText(await readFile(descriptorTarget, "utf8")) !== renderedDescriptor) throw new Error("outcome profile contract descriptor drift; run node scripts/build-outcome-profile-contract.mjs");
  if (normalizeText(await readFile(sourceTarget, "utf8")) !== renderedSource) throw new Error("outcome profile contract source drift; run node scripts/build-outcome-profile-contract.mjs");
} else {
  await writeFile(descriptorTarget, renderedDescriptor, "utf8");
  await writeFile(sourceTarget, renderedSource, "utf8");
}

function renderSource(value) {
  return `/** Generated by scripts/build-outcome-profile-contract.mjs. */\nexport interface OutcomeProfileContractV1 {\n  readonly v: "reelier.outcome-profile-contract/v1";\n  readonly domain: "reelier.outcome-profile-contract/v1\\\\0";\n  readonly members: readonly Readonly<{ path: string; digest: string }>[];\n  readonly digest: string;\n}\n\nconst generatedContract: OutcomeProfileContractV1 = ${JSON.stringify(value, null, 2)};\nexport const OUTCOME_PROFILE_CONTRACT_V1: OutcomeProfileContractV1 = Object.freeze({ ...generatedContract, members: Object.freeze(generatedContract.members.map(member => Object.freeze({ ...member }))) });\nexport const OUTCOME_PROFILE_CONTRACT_V1_DIGEST = OUTCOME_PROFILE_CONTRACT_V1.digest;\n`;
}

function normalizeText(text) {
  return text.replace(/\r\n/g, "\n");
}

function normalizeBytes(bytes) {
  return Buffer.from(normalizeText(bytes.toString("utf8")), "utf8");
}
