import canonicalize from "canonicalize";
import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const contractDirectory = fileURLToPath(new URL("../contract/bootstrap/v1/", import.meta.url));
const descriptorTarget = join(contractDirectory, "contract-descriptor.json");
const sourceTarget = fileURLToPath(new URL("../src/bootstrap/contract.ts", import.meta.url));
const members = [
  "agent-project.schema.json",
  "authority-cell-session-binding.schema.json",
  "bootstrap-report.schema.json",
  "route-coverage.schema.json",
  "runtime-descriptor.schema.json",
  "supervisor-status.schema.json",
];

if (members.join("\0") !== [...members].sort().join("\0")) throw new Error("bootstrap contract members must be sorted");
if (new Set(members).size !== members.length) throw new Error("bootstrap contract members must be unique");
if (members.some(member => member.includes("/") || member.includes("\\") || member === "." || member === "..")) throw new Error("bootstrap contract member path is invalid");
const actual = (await readdir(contractDirectory, { withFileTypes: true })).filter(entry => entry.isFile() && entry.name !== "contract-descriptor.json").map(entry => entry.name).sort();
if (actual.join("\0") !== members.join("\0")) throw new Error("bootstrap contract membership drift");
const digestedMembers = await Promise.all(members.map(async path => ({ path, digest: `sha256:${createHash("sha256").update(normalizeBytes(await readFile(join(contractDirectory, path)))).digest("hex")}` })));
const unsigned = { v: "reelier.bootstrap-contract/v1", domain: "reelier.bootstrap-contract/v1\\0", members: digestedMembers };
const descriptor = { ...unsigned, digest: `sha256:${createHash("sha256").update(canonicalize(unsigned), "utf8").digest("hex")}` };
const renderedDescriptor = `${JSON.stringify(descriptor, null, 2)}\n`;
const renderedSource = renderSource(descriptor);

if (process.argv.includes("--check")) {
  if (normalizeText(await readFile(descriptorTarget, "utf8")) !== renderedDescriptor) throw new Error("bootstrap contract descriptor drift; run node scripts/build-bootstrap-contract.mjs");
  if (normalizeText(await readFile(sourceTarget, "utf8")) !== renderedSource) throw new Error("bootstrap contract source drift; run node scripts/build-bootstrap-contract.mjs");
} else {
  await writeFile(descriptorTarget, renderedDescriptor, "utf8");
  await writeFile(sourceTarget, renderedSource, "utf8");
}

function renderSource(value) {
  return [
    "/** Generated by scripts/build-bootstrap-contract.mjs. */",
    'import canonicalize from "canonicalize";',
    'import { createHash } from "node:crypto";',
    'import { assertOwnDataTree } from "./normalize.js";',
    "",
    "export interface BootstrapContractV1 {",
    '  readonly v: "reelier.bootstrap-contract/v1";',
    '  readonly domain: "reelier.bootstrap-contract/v1\\\\0";',
    "  readonly members: readonly Readonly<{ path: string; digest: string }>[];",
    "  readonly digest: string;",
    "}",
    "",
    `const generatedContract: BootstrapContractV1 = ${JSON.stringify(value, null, 2)};`,
    "export const BOOTSTRAP_CONTRACT_V1: BootstrapContractV1 = freezeContract(generatedContract);",
    "export const BOOTSTRAP_CONTRACT_V1_DIGEST = BOOTSTRAP_CONTRACT_V1.digest;",
    "",
    "export function verifyBootstrapContractV1(value: unknown, files: ReadonlyMap<string, Uint8Array>): BootstrapContractV1 {",
    '  assertOwnDataTree(value, "bootstrap contract descriptor");',
    '  if (!value || typeof value !== "object") throw new TypeError("invalid bootstrap contract descriptor");',
    "  const descriptor = value as { v?: unknown; domain?: unknown; members?: unknown; digest?: unknown };",
    '  if (descriptor.v !== "reelier.bootstrap-contract/v1" || descriptor.domain !== "reelier.bootstrap-contract/v1\\\\0" || !Array.isArray(descriptor.members) || typeof descriptor.digest !== "string") throw new TypeError("invalid bootstrap contract shape");',
    "  const members = descriptor.members.map(member => {",
    '    if (!member || typeof member !== "object" || typeof (member as { path?: unknown }).path !== "string" || typeof (member as { digest?: unknown }).digest !== "string") throw new TypeError("invalid bootstrap contract member");',
    "    return member as { path: string; digest: string };",
    "  });",
    "  const paths = members.map(member => member.path);",
    '  if (paths.join("\\0") !== [...paths].sort().join("\\0") || new Set(paths).size !== paths.length || paths.join("\\0") !== BOOTSTRAP_CONTRACT_V1.members.map(member => member.path).join("\\0")) throw new TypeError("invalid bootstrap contract membership");',
    "  for (const member of members) {",
    "    const bytes = files.get(member.path);",
    '    if (!bytes || `sha256:${createHash("sha256").update(normalizeBytes(bytes)).digest("hex")}` !== member.digest) throw new TypeError(`invalid bootstrap contract member digest: ${member.path}`);',
    "  }",
    "  const unsigned = { v: descriptor.v, domain: descriptor.domain, members: members.map(member => ({ path: member.path, digest: member.digest })) };",
    "  const canonical = canonicalize(unsigned);",
    '  if (canonical === undefined) throw new TypeError("invalid bootstrap contract canonical form");',
    '  const expected = `sha256:${createHash("sha256").update(canonical, "utf8").digest("hex")}`;',
    '  if (descriptor.digest !== expected || /^sha256:0{64}$/.test(descriptor.digest)) throw new TypeError("invalid bootstrap contract aggregate digest");',
    "  return freezeContract({ ...unsigned, digest: descriptor.digest } as BootstrapContractV1);",
    "}",
    "",
    "function freezeContract(value: BootstrapContractV1): BootstrapContractV1 { return Object.freeze({ ...value, members: Object.freeze(value.members.map(member => Object.freeze({ ...member }))) }); }",
    'function normalizeBytes(bytes: Uint8Array): Buffer { return Buffer.from(Buffer.from(bytes).toString("utf8").replace(/\\r\\n/g, "\\n"), "utf8"); }',
    "",
  ].join("\n");
}

function normalizeText(text) { return text.replace(/\r\n/g, "\n"); }
function normalizeBytes(bytes) { return Buffer.from(normalizeText(bytes.toString("utf8")), "utf8"); }
